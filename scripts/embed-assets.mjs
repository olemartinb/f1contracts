// Post-build step: packs every file in dist/ into worker/assets.generated.js so the Worker
// serves the site from its own code. Deploying then needs only an API token (no asset upload).
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const out = path.join(root, 'worker', 'assets.generated.js');

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json',
  '.webmanifest': 'application/manifest+json',
  '.xml': 'application/xml; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.ico': 'image/x-icon',
};
const SKIP = new Set(['_headers', '_redirects']);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)])),
  );
  return files.flat();
}

const files = (await walk(dist)).filter((f) => !SKIP.has(path.basename(f))).sort();
const lines = [];
let total = 0;
for (const file of files) {
  const urlPath = '/' + path.relative(dist, file).split(path.sep).join('/');
  const type = TYPES[path.extname(file)];
  if (!type) throw new Error(`No content type for ${urlPath}; add its extension to scripts/embed-assets.mjs`);
  const body = await readFile(file);
  total += body.length;
  const etag = `"${createHash('sha256').update(body).digest('base64url').slice(0, 22)}"`;
  // Text stays as text (compresses far better than base64); binary files are base64.
  const isText = /^(text\/|application\/(json|xml|manifest))|svg/.test(type);
  const payload = isText ? `text: ${JSON.stringify(body.toString('utf8'))}` : `b64: ${JSON.stringify(body.toString('base64'))}`;
  lines.push(`  ${JSON.stringify(urlPath)}: { type: ${JSON.stringify(type)}, etag: ${JSON.stringify(etag)}, ${payload} },`);
}
await writeFile(out, `// Generated by scripts/embed-assets.mjs. Do not edit.\nexport default {\n${lines.join('\n')}\n};\n`);
console.log(`Embedded ${files.length} files (${(total / 1024).toFixed(0)} kB) into worker/assets.generated.js`);
